import { useCallback, useEffect, useRef, useState } from 'react'
import { ApiError, api, isTerminalSearch } from './api'
import type { ClarificationQuestion, PublicConfig, SearchRequest } from './api'
import { Progress } from './components/Progress'
import { Results } from './components/Results'
import { SearchForm } from './components/SearchForm'
import { useSearchPolling } from './usePolling'

const readIdFromUrl = () => new URLSearchParams(window.location.search).get('s')

export default function App() {
  const [config, setConfig] = useState<PublicConfig | null>(null)
  const [configError, setConfigError] = useState<string | null>(null)
  const [searchId, setSearchId] = useState<string | null>(readIdFromUrl())
  const [busy, setBusy] = useState(false)
  const [formError, setFormError] = useState<{ field: string | null; message: string } | null>(null)
  const [clarification, setClarification] = useState<ClarificationQuestion[] | null>(null)
  const [notice, setNotice] = useState<string | null>(null)
  // The access key is held only in memory for cancelling; it is never persisted.
  const accessKey = useRef('')

  const { search, results, error, connectionLost } = useSearchPolling(searchId)

  useEffect(() => {
    api.config().then(setConfig, (e: ApiError) => setConfigError(e.message))
  }, [])

  const start = useCallback(async (request: SearchRequest, key: string) => {
    setBusy(true)
    setFormError(null)
    setClarification(null)
    setNotice(null)
    accessKey.current = key
    try {
      const created = await api.createSearch(request, key)
      if (created.status === 'NEEDS_CLARIFICATION') {
        setClarification(created.clarification?.questions ?? [])
      } else if (created.status === 'FAILED') {
        setNotice(created.message ?? 'No consenting businesses are available for this search.')
      } else {
        window.history.pushState(null, '', `?s=${created.search_id}`)
        setSearchId(created.search_id)
      }
    } catch (e) {
      const err = e as ApiError
      setFormError({ field: err.field ?? null, message: err.message })
    } finally {
      setBusy(false)
    }
  }, [])

  const cancel = useCallback(async () => {
    if (!searchId) return
    try {
      await api.cancel(searchId, accessKey.current)
      setNotice('Cancelled. No further calls will be made; any call already in progress will finish.')
    } catch (e) {
      setNotice((e as ApiError).message)
    }
  }, [searchId])

  const reset = () => {
    window.history.pushState(null, '', window.location.pathname)
    setSearchId(null)
    setNotice(null)
    setFormError(null)
    setClarification(null)
  }

  const running = !!search && !isTerminalSearch(search.status)

  return (
    <div className="mx-auto grid max-w-3xl gap-5 px-4 py-6 sm:py-10">
      <header>
        <p className="flex items-center gap-3 text-sm font-semibold uppercase tracking-widest text-[var(--accent)]">
          <span className="ping" aria-hidden="true" /> Sonar
        </p>
        <h1 className="mt-2 text-3xl font-extrabold sm:text-4xl">Search the real world by calling it.</h1>
        <p className="mt-2 text-[var(--muted)]">
          Sonar phones a few consenting shops for you, asks one short question, and shows exactly what
          each one said, when, with the evidence. Silence is never treated as "no".
        </p>
      </header>

      {search?.demo_mode && (
        <div
          role="status"
          className="rounded-xl border-2 border-[var(--warn)] bg-[var(--warn-bg)] px-4 py-3 font-semibold text-[var(--warn)]"
        >
          SIMULATED: these are not real calls. Every result below is generated by the simulator.
        </div>
      )}

      {connectionLost && (
        <div role="alert" className="rounded-xl bg-[var(--bad-bg)] px-4 py-2 text-sm text-[var(--bad)]">
          Connection lost, retrying. The last results stay on screen. ({error})
        </div>
      )}
      {notice && (
        <div role="status" className="rounded-xl bg-[var(--info-bg)] px-4 py-2 text-sm text-[var(--info)]">
          {notice}
        </div>
      )}

      {!searchId && (
        <>
          {config ? (
            <SearchForm
              config={config}
              busy={busy}
              fieldError={formError}
              clarification={clarification}
              onSubmit={start}
            />
          ) : (
            <p className="card p-5 text-[var(--muted)]" role="status">
              {configError ? `Cannot reach the Sonar server: ${configError}` : 'Loading…'}
            </p>
          )}
        </>
      )}

      {searchId && !search && !error && (
        <p className="card p-5 text-[var(--muted)]" role="status">
          Loading search…
        </p>
      )}
      {searchId && !search && error && !connectionLost && (
        <div role="alert" className="card p-5">
          <p className="font-semibold">{error}</p>
          <button className="btn mt-3" onClick={reset}>
            New search
          </button>
        </div>
      )}

      {search && (
        <>
          {search.status === 'FAILED' && search.error && (
            <div role="alert" className="card p-5">
              <p className="font-semibold">This search could not run.</p>
              <p className="text-sm text-[var(--muted)]">{search.error.message}</p>
            </div>
          )}
          <Progress search={search} running={running} onCancel={cancel} />
          {results && (
            <Results
              results={results.results}
              complete={results.complete}
              explanation={results.ranking_explanation}
            />
          )}
          {!running && (
            <button className="btn btn-primary justify-self-start" onClick={reset}>
              New search
            </button>
          )}
        </>
      )}

      <footer className="text-xs text-[var(--muted)]">
        Sonar reports what a business said by phone. It does not guarantee it, and it does not give
        medical advice.
      </footer>
    </div>
  )
}
